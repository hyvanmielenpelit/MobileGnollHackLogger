using Sentry;
using Sentry.Extensibility;
using System.Net;
using Microsoft.AspNetCore.Http;
using System.Net.Http;
using System;
using System.Linq;
using Overseer.Services.Providers;

namespace Overseer.Services
{
    public class AuthSentryEventProcessor : ISentryEventProcessor
    {
        private readonly IHttpContextAccessor _httpContextAccessor;

        private static readonly string[] AiProviderHosts = GoogleProvider.ProviderHosts
            .Concat(AnthropicProvider.ProviderHosts)
            .Concat(OpenAiResponsesProvider.ProviderHosts)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToArray();

        public AuthSentryEventProcessor(IHttpContextAccessor httpContextAccessor)
        {
            _httpContextAccessor = httpContextAccessor;
        }

        public SentryEvent? Process(SentryEvent @event)
        {
            var httpContext = _httpContextAccessor.HttpContext;

            if (httpContext != null && httpContext.User?.Identity?.IsAuthenticated != true)
            {
                // Drop events from unauthenticated web requests (bots, probes)
                return null;
            }

            bool isAiProvider = IsAiProviderTarget(@event);

            // Check if the event or its inner exceptions contain a transient HttpRequestException
            if (IsTransientApiOverloadException(@event.Exception, isAiProvider))
            {
                return null;
            }

            // Check if the event was generated by SentryHttpFailedRequestHandler for transient AI provider responses
            if (IsTransientHttpFailedRequestEvent(@event, isAiProvider))
            {
                return null;
            }

            return @event;
        }

        private bool IsAiProviderTarget(SentryEvent @event)
        {
            string? url = @event.Request?.Url;
            if (string.IsNullOrEmpty(url) && @event.Tags.TryGetValue("url", out var tagUrl))
            {
                url = tagUrl;
            }
            if (string.IsNullOrEmpty(url) && @event.Tags.TryGetValue("Uri", out var tagUri))
            {
                url = tagUri;
            }

            if (!string.IsNullOrEmpty(url) && AiProviderHosts.Any(host => url.Contains(host, StringComparison.OrdinalIgnoreCase)))
            {
                return true;
            }

            return IsAiProviderException(@event.Exception);
        }

        private bool IsAiProviderException(Exception? exception)
        {
            if (exception == null)
            {
                return false;
            }

            if (exception is HttpRequestException httpEx && !string.IsNullOrEmpty(httpEx.Message))
            {
                if (AiProviderHosts.Any(host => httpEx.Message.Contains(host, StringComparison.OrdinalIgnoreCase)))
                {
                    return true;
                }
            }

            if (exception is AggregateException aggEx)
            {
                foreach (var inner in aggEx.InnerExceptions)
                {
                    if (IsAiProviderException(inner))
                    {
                        return true;
                    }
                }
            }
            else if (exception.InnerException != null)
            {
                return IsAiProviderException(exception.InnerException);
            }

            return false;
        }

        private bool IsTransientApiOverloadException(Exception? exception, bool isAiProvider)
        {
            if (exception == null)
            {
                return false;
            }

            if (exception is HttpRequestException httpEx)
            {
                // Globally drop standard transient overload status codes
                if (httpEx.StatusCode == HttpStatusCode.TooManyRequests || 
                    httpEx.StatusCode == HttpStatusCode.BadGateway || 
                    httpEx.StatusCode == HttpStatusCode.ServiceUnavailable ||
                    httpEx.StatusCode == HttpStatusCode.GatewayTimeout ||
                    (int?)httpEx.StatusCode == 529)
                {
                    return true;
                }

                // For AI providers, drop ALL 5xx server errors (including 500, 501)
                if (isAiProvider && httpEx.StatusCode.HasValue && (int)httpEx.StatusCode.Value >= 500 && (int)httpEx.StatusCode.Value <= 599)
                {
                    return true;
                }

                if (httpEx.Message != null)
                {
                    if (httpEx.Message.Contains("503") ||
                        httpEx.Message.Contains("502") ||
                        httpEx.Message.Contains("429") ||
                        httpEx.Message.Contains("504") ||
                        httpEx.Message.Contains("529"))
                    {
                        return true;
                    }

                    if (isAiProvider && (httpEx.Message.Contains("500") || httpEx.Message.Contains("501")))
                    {
                        return true;
                    }
                }
            }

            if (exception is AggregateException aggEx)
            {
                foreach (var inner in aggEx.InnerExceptions)
                {
                    if (IsTransientApiOverloadException(inner, isAiProvider))
                    {
                        return true;
                    }
                }
            }
            else if (exception.InnerException != null)
            {
                return IsTransientApiOverloadException(exception.InnerException, isAiProvider);
            }

            return false;
        }

        private bool IsTransientHttpFailedRequestEvent(SentryEvent @event, bool isAiProvider)
        {
            bool isHttpFailedRequestHandler = false;

            if (@event.SentryExceptions?.Any(e => string.Equals(e.Mechanism?.Type, "SentryHttpFailedRequestHandler", StringComparison.OrdinalIgnoreCase)) == true)
            {
                isHttpFailedRequestHandler = true;
            }
            else if (@event.Tags.TryGetValue("mechanism", out var mechanism) && string.Equals(mechanism, "SentryHttpFailedRequestHandler", StringComparison.OrdinalIgnoreCase))
            {
                isHttpFailedRequestHandler = true;
            }
            else if (@event.Message?.Formatted?.Contains("Response status code does not indicate success", StringComparison.OrdinalIgnoreCase) == true)
            {
                isHttpFailedRequestHandler = true;
            }

            if (!isHttpFailedRequestHandler)
            {
                return false;
            }

            // Extract HTTP status code
            int? statusCode = null;
            if (@event.Contexts.Response?.StatusCode.HasValue == true)
            {
                statusCode = (int)@event.Contexts.Response.StatusCode.Value;
            }
            else if (@event.Tags.TryGetValue("response.status_code", out var codeStr) && int.TryParse(codeStr, out var parsedCode))
            {
                statusCode = parsedCode;
            }
            else if (@event.Tags.TryGetValue("status_code", out var codeStr2) && int.TryParse(codeStr2, out var parsedCode2))
            {
                statusCode = parsedCode2;
            }
            else if (@event.Message?.Formatted != null)
            {
                var msg = @event.Message.Formatted;
                if (msg.Contains("503")) statusCode = 503;
                else if (msg.Contains("502")) statusCode = 502;
                else if (msg.Contains("429")) statusCode = 429;
                else if (msg.Contains("504")) statusCode = 504;
                else if (msg.Contains("529")) statusCode = 529;
                else if (msg.Contains("500")) statusCode = 500;
                else if (msg.Contains("501")) statusCode = 501;
            }

            // Drop transient overload status codes and all 5xx for AI providers
            if (isAiProvider && statusCode.HasValue)
            {
                if (statusCode == 429 || (statusCode >= 500 && statusCode <= 599))
                {
                    return true;
                }
            }

            return false;
        }
    }
}
